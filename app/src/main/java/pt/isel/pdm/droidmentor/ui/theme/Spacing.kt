package pt.isel.pdm.droidmentor.ui.theme // Groups the theme code.

import androidx.compose.ui.unit.dp // Creates sizes in density-independent pixels.

/** Shared spacing values for DroidMentor layouts. */
object DroidMentorSpacing { // Keeps shared spacing values in one place.
    /** Compact spacing between closely related elements. */
    val extraSmall = 4.dp // A small gap of 4 density-independent pixels.

    /** Spacing within a group of controls. */
    val small = 8.dp // An 8 dp gap between related controls.

    /** Standard padding for cards and list items. */
    val medium = 16.dp // Standard 16 dp padding for cards and list items.

    /** Standard horizontal screen padding. */
    val large = 24.dp // Standard 24 dp screen padding.

    /** Spacing between distinct screen sections. */
    val extraLarge = 32.dp // A 32 dp gap between screen sections.
} // Ends this block.
