package pt.isel.pdm.droidmentor.data.local // Groups the app's local database components.

import android.content.Context // Provides the app storage location to Room.
import androidx.room.Database // Declares the entities and schema version.
import androidx.room.Room // Builds the database implementation generated by Room.
import androidx.room.RoomDatabase // Supplies the base database behaviour.
import androidx.room.TypeConverters // Makes our enum converters available to the database.
import pt.isel.pdm.droidmentor.data.local.converter.MessageConverters // Converts message enums to stored text.
import pt.isel.pdm.droidmentor.data.local.dao.ChatDao // Provides the chat operations.
import pt.isel.pdm.droidmentor.data.local.dao.MessageDao // Provides the message operations.
import pt.isel.pdm.droidmentor.data.local.entity.ChatEntity // Defines the chats table.
import pt.isel.pdm.droidmentor.data.local.entity.MessageEntity // Defines the messages table.

/** Stores DroidMentor chat history using schema version 1. */
@Database( // Lets Room generate and validate the database implementation.
    entities = [ChatEntity::class, MessageEntity::class], // Registers the two history tables.
    version = 1, // Starts the shipped schema at version one.
    exportSchema = true, // Writes the schema JSON used to review and test later changes.
) // Ends the schema settings.
@TypeConverters(MessageConverters::class) // Uses the same enum conversions throughout the database.
abstract class DroidMentorDatabase : RoomDatabase() { // Exposes the generated database through a simple class.
    /** Returns the DAO that reads and changes chat rows. */
    abstract fun chatDao(): ChatDao // Provides the generated chat operations.

    /** Returns the DAO that observes histories and saves message exchanges. */
    abstract fun messageDao(): MessageDao // Provides the generated message operations.

    /** Keeps the file name and database creation method together. */
    companion object { // Allows the service locator to create the database later.
        /** Stable file name used for the app's saved chat history. */
        const val DATABASE_NAME = "droidmentor.db" // Reuses the same database file across app launches.

        /**
         * Builds the persistent database without allowing main-thread queries or destructive migrations.
         *
         * @param context Context whose application storage will hold the file.
         * @param fileName Database file name; tests use a separate name to protect user data.
         */
        fun create(context: Context, fileName: String = DATABASE_NAME): DroidMentorDatabase { // Creates a Room instance for this file.
            return Room.databaseBuilder( // Uses a disk-backed database rather than an in-memory one.
                context.applicationContext, // Keeps the app context instead of retaining an Activity.
                DroidMentorDatabase::class.java, // Loads this database's generated implementation.
                fileName, // Chooses the stable app file or a separate file supplied by a test.
            ).build() // Keeps Room's safe defaults; the first DAO query opens the database.
        } // Ends the creation method.
    } // Ends the companion object.
} // Ends the app database class.
